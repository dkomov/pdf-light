"""Generate an original, deterministic PDF for screenshots and integration checks."""

import argparse
import math
from pathlib import Path

from pypdf import PdfWriter
from pypdf.generic import DecodedStreamObject, DictionaryObject, NameObject


def make_demo(destination):
    writer = PdfWriter()
    font = writer._add_object(
        DictionaryObject(
            {
                NameObject("/Type"): NameObject("/Font"),
                NameObject("/Subtype"): NameObject("/Type1"),
                NameObject("/BaseFont"): NameObject("/Helvetica"),
            }
        )
    )
    bold = writer._add_object(
        DictionaryObject(
            {
                NameObject("/Type"): NameObject("/Font"),
                NameObject("/Subtype"): NameObject("/Type1"),
                NameObject("/BaseFont"): NameObject("/Helvetica-Bold"),
            }
        )
    )
    page = writer.add_blank_page(width=720, height=900)
    content = [b"0.965 0.957 0.929 rg 0 0 720 900 re f"]

    def text(x, y, size, value, strong=False):
        value = value.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
        content.append(
            f"0.12 0.20 0.19 rg BT /{'B' if strong else 'F'} {size} Tf 1 0 0 1 {x} {y} Tm ({value}) Tj ET".encode()
        )

    text(54, 840, 12, "PDF LIGHT  /  FIELD NOTES", True)
    text(54, 746, 59, "Less weight.", True)
    text(54, 680, 59, "Same story.", True)
    text(56, 635, 16, "A small experiment in thoughtful PDF optimization.")
    content.append(b"q 54 176 612 406 re W n 0.12 0.30 0.28 RG 0.65 w")
    for row in range(74):
        points = []
        for col in range(151):
            x = 54 + col * 4.08
            y = 192 + row * 5.0 + 37 * math.sin(col / 18 + row / 23) * math.sin(col / 48)
            points.append(f"{x:.12f} {y:.12f} {'m' if col == 0 else 'l'}")
        content.append((" ".join(points) + " S").encode())
    content.append(b"Q")
    text(54, 120, 12, "VECTOR FIRST", True)
    text(270, 120, 12, "LOCAL BY DESIGN", True)
    text(510, 120, 12, "OPEN SOURCE", True)
    text(54, 65, 10, "Original synthetic artwork. Generated by PDF Light. No private documents.")
    stream = DecodedStreamObject()
    stream.set_data(b"\n".join(content))
    page[NameObject("/Contents")] = writer._add_object(stream)
    page[NameObject("/Resources")] = DictionaryObject(
        {NameObject("/Font"): DictionaryObject({NameObject("/F"): font, NameObject("/B"): bold})}
    )
    page.compress_content_streams(level=9)
    writer.add_metadata({"/Title": "Less weight. Same story.", "/Author": "PDF Light contributors"})
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("xb") as stream:
        writer.write(stream)
    print(destination)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    make_demo(parser.parse_args().output)
